import { test, expect } from '@playwright/test'

test('条件编辑、对话归档和恢复形成完整闭环', async ({ page }) => {
  await page.goto('/#/chat')
  await page.getByRole('button', { name: '编辑找房条件', exact: true }).first().click()
  const conditions = page.getByRole('dialog', { name: '找房条件' })
  await conditions.getByRole('textbox', { name: '工作地点' }).fill('金科路')
  await conditions.getByRole('button', { name: '步行', exact: true }).click()
  await conditions.getByRole('button', { name: '30 分钟', exact: true }).click()
  await conditions.getByRole('button', { name: '填入对话' }).click()
  await expect(page.getByRole('textbox', { name: '找房需求' })).toHaveValue(/金科路.*30分钟/)
  await page.getByRole('button', { name: '发送消息' }).click()
  await page.getByRole('button', { name: '新建对话' }).click()
  await expect(page.locator('.message.user')).toHaveCount(0)
  await page.getByRole('button', { name: '查看历史对话' }).click()
  await page.getByRole('dialog', { name: '历史对话' }).getByRole('button', { name: /金科路/ }).click()
  await expect(page.locator('.message.user')).toHaveCount(1)
})

test('搜索、列表模式与租金排序可组合使用', async ({ page }) => {
  await page.goto('/#/map')
  await page.getByRole('button', { name: '列表模式' }).click()
  await page.getByRole('searchbox', { name: '搜索区域、小区或地铁' }).fill('金科路')
  await page.getByRole('combobox', { name: '房源排序' }).selectOption('rent-asc')
  await expect(page.locator('.map-homes .property-card')).toHaveCount(2)
  await expect(page.locator('.map-homes .property-card').first()).toContainText('¥4,600')
  await page.getByRole('searchbox', { name: '搜索区域、小区或地铁' }).fill('没有这个地方')
  await expect(page.getByRole('heading', { name: '没有找到合适的房源' })).toBeVisible()
  await page.getByRole('button', { name: '清空搜索' }).click()
  await expect(page.locator('.map-homes .property-card')).toHaveCount(6)
})

