test('生活模拟的工作日设置会改变月通勤总量', async ({ page }) => {
  await page.goto('/#/lifesim/commute')
  await expect(page.getByTestId('monthly-commute')).toContainText('8.8')
  await page.getByRole('button', { name: '增加工作日' }).click()
  await expect(page.getByTestId('monthly-commute')).toContainText('9.2')
  await page.getByRole('button', { name: '减少工作日' }).click()
  await expect(page.getByTestId('monthly-commute')).toContainText('8.8')
})
