test('从收藏中移除后重排分页，不漏掉下一条房源',async({page})=>{
  await signup(page,'/favorites')
  const token=await page.evaluate(()=>JSON.parse(localStorage.getItem('rentpilot-account-v1')!).token)
  for(let i=1;i<=21;i++){const response=await page.request.put(`/api/me/favorites/SH-MOCK-${String(i).padStart(6,'0')}`,{headers:{Authorization:`Bearer ${token}`}});expect(response.status()).toBe(204)}
  await page.reload()
  await expect(page.getByTestId('catalog-card')).toHaveCount(20)
  const removed=await page.getByTestId('catalog-card').first().getAttribute('data-id')
  await page.locator('.rental-card').first().getByRole('button').click()
  await expect(page.locator(`[data-id="${removed}"]`)).toHaveCount(0)
  await expect(page.getByTestId('catalog-card')).toHaveCount(20)
  await expect(page.getByRole('button',{name:'加载更多',exact:true})).toHaveCount(0)
})

