test('另一标签切换账户后关闭旧账户的清空确认，保留新账户历史',async({page,context})=>{
  await signup(page,'/listing/SH-MOCK-000001','甲租客')
  await expect(page.locator('.real-detail')).toBeVisible()
  await page.goto('/#/recent')
  await expect(page.getByTestId('catalog-card')).toHaveCount(1)
  await page.getByRole('button',{name:'清空',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'清空浏览记录'})
  await expect(dialog).toBeVisible()
  const second=await context.newPage()
  await signup(second,'/listing/SH-MOCK-000201','乙租客')
  await expect(second.locator('.real-detail')).toBeVisible()
  await second.goto('/#/recent')
  await expect(second.getByTestId('catalog-card')).toHaveCount(1)
  await expect(dialog).toBeHidden()
  await page.reload()
  await expect(page.getByTestId('catalog-card')).toHaveAttribute('data-id','SH-MOCK-000201')
  await second.reload()
  await expect(second.getByTestId('catalog-card')).toHaveCount(1)
})

