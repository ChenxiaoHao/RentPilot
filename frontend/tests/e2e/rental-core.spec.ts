import { test, expect, type Page } from '@playwright/test'

async function signup(page: Page, redirect = '/listings', nickname = '测试租客') {
  const username = `u${Date.now().toString(36)}${Math.random().toString(36).slice(2,6)}`
  await page.goto(`/#/account?mode=register&redirect=${encodeURIComponent(redirect)}`)
  await page.getByRole('textbox', { name: '用户名', exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('Test-pass-123')
  await page.getByRole('textbox', { name: '昵称', exact: true }).fill(nickname)
  await page.getByRole('button', { name: '创建账号', exact: true }).click()
  await expect(page).not.toHaveURL(/#\/account/)
  return username
}

async function createViewing(page: Page, listingId = 'SH-MOCK-000001') {
  const token = await page.evaluate(() => JSON.parse(localStorage.getItem('rentpilot-account-v1')!).token)
  const response = await page.request.post('/api/me/viewings', { headers: { Authorization: `Bearer ${token}` }, data: { listingId, date: new Date(Date.now() + 86400000 * 2).toISOString().slice(0, 10), slot: 'MORNING' } })
  expect(response.ok()).toBeTruthy()
}
test('账号、详情、收藏、历史、计划构成可持久化闭环', async ({ page }) => {
  await signup(page)
  await page.getByTestId('catalog-card').first().click()
  await expect(page).toHaveURL(/#\/listing\/SH-MOCK-/)
  await expect(page.getByRole('heading', { name: '潍坊一村 · 合租单间', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '收藏房源', exact: true }).click()
  await expect(page.getByRole('button', { name: '取消收藏房源', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await createViewing(page)
  await page.goto('/#/favorites')
  await expect(page.getByTestId('catalog-card')).toHaveCount(1)
  await page.reload()
  await expect(page.getByTestId('catalog-card')).toHaveCount(1)
  await page.goto('/#/viewings')
  await expect(page.getByTestId('viewing-card')).toHaveCount(1)
  await page.getByRole('button', { name: '取消计划', exact: true }).click()
  await page.getByRole('dialog', { name: '取消看房计划' }).getByRole('button', { name: '确认取消', exact: true }).click()
  await expect(page.getByTestId('viewing-card')).toHaveCount(0)
  await page.getByRole('tab', { name: '已取消', exact: true }).click()
  await expect(page.getByTestId('viewing-card')).toHaveCount(1)
  await page.goto('/#/recent')
  await expect(page.getByTestId('catalog-card')).toHaveCount(1)
  await page.goto('/#/profile')
  await expect(page.getByRole('heading', { name: '测试租客', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('dialog', { name: '退出登录' }).getByRole('button', { name: '确认退出', exact: true }).click()
  await page.goto('/#/favorites')
  await expect(page.getByRole('heading', { name: '登录后查看收藏', exact: true })).toBeVisible()
  await expect(page.getByTestId('catalog-card')).toHaveCount(0)
})

