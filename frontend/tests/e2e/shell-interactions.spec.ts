import { test, expect } from '@playwright/test'

test('map keeps a surviving marker in place and selects a visible result after filtering', async ({ page }) => {
  await page.goto('/#/map')
  const tangzhen = page.getByRole('button', { name: '唐镇新苑 · 舒适一居室 ¥3,800' })
  const initialPosition = await tangzhen.getAttribute('style')
  await page.getByRole('button', { name: '张江高科小区 · 经典一室一厅 ¥4,800' }).click()
  await page.getByRole('combobox', { name: '租金预算' }).selectOption('4200')
  await expect(tangzhen).toHaveAttribute('aria-pressed', 'true')
  await expect(tangzhen).toHaveAttribute('style', initialPosition!)
  await expect(page.getByRole('status').filter({ hasText: '当前选中' })).toContainText('唐镇新苑')
  await page.getByRole('combobox', { name: '户型筛选' }).selectOption('two')
  await expect(page.locator('.price-pin[aria-pressed="true"]')).toHaveCount(0)
  await expect(page.getByText('0 套模拟房源', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '重置地图筛选' }).click()
  await expect(page.getByRole('button', { name: '张江高科小区 · 经典一室一厅 ¥4,800' })).toHaveAttribute('aria-pressed', 'true')
})

test('listing expands its one illustration and confirms a clearly local appointment demo', async ({ page }) => {
  await page.goto('/#/listing/h1')
  await page.getByRole('button', { name: '放大房源设计示意图' }).click()
  const imageDialog = page.getByRole('dialog', { name: '房源设计示意图' })
  await expect(imageDialog.getByRole('img')).toBeVisible()
  await expect(imageDialog).toContainText('1 / 1')
  await page.keyboard.press('Escape')
  await expect(imageDialog).toBeHidden()
  await page.getByRole('button', { name: '预约线下看房（演示）' }).click()
  const booking = page.getByRole('dialog', { name: '预约看房演示' })
  await expect(booking).toContainText('不会提交真实预约')
  await booking.getByRole('button', { name: '保存看房计划' }).click()
  await expect(booking).toBeHidden()
  await expect(page.getByRole('status')).toContainText('未提交任何真实看房预约')
  await page.getByRole('button', { name: '咨询演示', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '咨询服务演示' })).toContainText('尚未接入真实经纪人')
})

test('profile opens accessible local panels and persists its notification preference', async ({ page }) => {
  await page.goto('/#/demo/profile')
  const savedButton = page.locator('.management-item').filter({ hasText: '收藏房源' })
  await savedButton.click()
  const saved = page.getByRole('dialog', { name: '我的收藏' })
  await expect(saved.getByRole('link', { name: /去发现房源/ })).toBeVisible()
  await expect(savedButton).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(savedButton).toHaveAttribute('aria-expanded', 'false')
  await expect(savedButton).toBeFocused()
  await page.getByRole('button', { name: '系统设置', exact: true }).click()
  const settings = page.getByRole('dialog', { name: '系统设置' })
  const notification = settings.getByRole('switch', { name: '本地 Mock 房源通知偏好' })
  await notification.click()
  await expect(notification).toHaveAttribute('aria-checked', 'true')
  await expect(settings).toContainText('不发送推送')
  await page.reload()
  await page.getByRole('button', { name: '系统设置', exact: true }).click()
  await expect(page.getByRole('switch', { name: '本地 Mock 房源通知偏好' })).toHaveAttribute('aria-checked', 'true')
})

test('negotiation supports arrow-key selection and applies only the confirmed tradeoff', async ({ page }) => {
  await page.goto('/#/negotiate')
  const options = page.getByRole('radiogroup', { name: '预算与通勤取舍方案' })
  const first = options.getByRole('radio', { name: /方案 A/ })
  const second = options.getByRole('radio', { name: /方案 B/ })
  await first.focus()
  await first.press('ArrowDown')
  await expect(second).toHaveAttribute('aria-checked', 'true')
  await expect(second).toBeFocused()
  await expect(page.getByRole('status').filter({ hasText: '已选定方案 B' })).toContainText('¥3,500')
  await page.getByRole('button', { name: '确认应用调整' }).click()
  await expect(page).toHaveURL(/#\/generating$/)
  await expect(page.getByRole('status').filter({ hasText: '已应用' })).toContainText('本地协商')
})

test('local generation keeps its next action stable and announces the active stage', async ({ page }) => {
  await page.goto('/#/generating')
  const next = page.getByRole('button', { name: '查看居住方案' })
  await expect(next).toBeVisible()
  await expect(next).toBeDisabled()
  await expect(page.locator('.generating')).toHaveAttribute('aria-busy', 'true')
  const status = page.getByRole('status').filter({ hasText: '理解居住需求' })
  await expect(status).toBeVisible()
  await expect(next).toBeEnabled({ timeout: 6000 })
  await expect(page.locator('.generating')).toHaveAttribute('aria-busy', 'false')
  await next.click()
  await expect(page).toHaveURL(/#\/plans$/)
})

test('empty state changes only the requested condition and retains local notification choice', async ({ page }) => {
  await page.goto('/#/empty?budget=3000&commute=12&district=唐镇&type=two&metro=2号线')
  await page.getByRole('switch', { name: '本地 Mock 房源变动提醒' }).click()
  await expect(page.getByRole('switch')).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('button', { name: '应用此建议' }).nth(1).click()
  await expect(page.getByRole('combobox', { name: '租金预算' })).toHaveValue('3000')
  await expect(page.getByRole('combobox', { name: '区域筛选' })).toHaveValue('唐镇')
  await expect(page.getByRole('combobox', { name: '户型筛选' })).toHaveValue('two')
  await expect(page.getByRole('combobox', { name: '地铁线路' })).toHaveValue('2号线')
  await expect(page.getByText('通勤 ≤40 分钟')).toBeVisible()
})
